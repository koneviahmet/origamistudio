export function categorizeVoxelPark(id) {
  if (id.startsWith('animal_')) return 'animal'
  if (id.startsWith('bike_')) return 'bike'
  if (id.startsWith('foliage_path_') || id === 'foliage_grass') return 'path'
  if (id.startsWith('foliage_')) return 'foliage'
  if (id.startsWith('park_')) return 'furnishing'
  if (id.startsWith('picnic_food_')) return 'food'
  if (id.startsWith('picnic_')) return 'picnic'
  if (id.startsWith('playground_')) return 'playground'
  return 'decor'
}


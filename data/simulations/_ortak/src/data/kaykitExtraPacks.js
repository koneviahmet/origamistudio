export function categorizeDungeon(id) {
  if (
    id.startsWith('wall_') ||
    id.startsWith('door_') ||
    id.startsWith('stairs_') ||
    id.startsWith('column') ||
    id === 'pillar' ||
    id.startsWith('pillar_') ||
    id.startsWith('arch')
  ) {
    return 'building'
  }
  if (id.startsWith('floor_')) return 'road'
  return 'prop'
}

export function categorizeForest(id) {
  if (id.startsWith('Tree_') || id.startsWith('Tree_Bare_')) return 'prop'
  return 'prop'
}

export function categorizeFurniture(id) {
  if (id.startsWith('bed_') || id.startsWith('cabinet_') || id.startsWith('shelf_')) {
    return 'building'
  }
  return 'prop'
}

export function categorizeHalloween(id) {
  if (id === 'crypt' || id === 'shrine' || id.startsWith('arch')) return 'building'
  if (id.startsWith('path_') || id.startsWith('floor_dirt')) return 'road'
  return 'prop'
}

export function categorizeMedieval(id) {
  if (id.startsWith('building_')) return 'building'
  if (
    id.startsWith('hex_road') ||
    id.startsWith('hex_grass') ||
    id.startsWith('hex_coast') ||
    id.startsWith('hex_river') ||
    id === 'hex_water'
  ) {
    return 'road'
  }
  return 'prop'
}

export function categorizeResource(id) {
  return 'prop'
}

export function categorizeRestaurant(id) {
  if (
    id.startsWith('food_') ||
    id.startsWith('stew_') ||
    id.startsWith('crate_steak') ||
    id.startsWith('crate_potatoes') ||
    id.startsWith('crate_carrots') ||
    id.startsWith('crate_lettuce') ||
    id.startsWith('crate_onions') ||
    id.startsWith('crate_ham') ||
    id.startsWith('crate_cheese') ||
    id.startsWith('crate_tomatoes') ||
    id.startsWith('crate_buns')
  ) {
    return 'food'
  }
  if (
    id.startsWith('stove_') ||
    id.startsWith('kitchencounter') ||
    id.startsWith('door_') ||
    id.startsWith('extractorhood')
  ) {
    return 'building'
  }
  return 'prop'
}

export function categorizeRpg(id) {
  return 'prop'
}


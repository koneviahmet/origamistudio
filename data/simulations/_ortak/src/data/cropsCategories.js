export function categorizeCrops(id) {
  if (/^(Apple|Orange|Coconut|Watermelon|BushBerries|Beet|Carrot|Corn|Lettuce|Tomato|Pumpkin)/.test(id)) {
    return 'produce'
  }
  return 'field'
}


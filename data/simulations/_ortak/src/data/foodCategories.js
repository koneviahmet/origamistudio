export function categorizeFood(id) {
  const legacy = FOOD_CATEGORY_LOOKUP[id] ?? 'other'
  return FOOD_CATEGORY_GROUP[legacy] ?? 'kitchen'
}

export const FOOD_IDS = Object.keys(FOOD_CATEGORY_LOOKUP).sort()

export function getFoodCategories() {
  return FOOD_CATEGORY_ORDER.map((id) => ({
    id,
    label: FOOD_CATEGORY_LABELS[id] ?? id,
  }))
}

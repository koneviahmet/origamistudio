export function categorizeSpace(id) {
  if (id.startsWith('corridor_') || id === 'corridor') return 'structure'
  if (id.startsWith('hangar_') || id.startsWith('rocket_')) return 'structure'
  if (id.startsWith('platform_')) return 'structure'
  if (
    id.startsWith('structure_') || id === 'structure' ||
    id.startsWith('supports_') || id.startsWith('stairs_') || id === 'stairs' ||
    id.startsWith('chimney') || id.startsWith('gate_') ||
    id === 'rail' || id.startsWith('rail_')
  ) return 'structure'
  if (id.startsWith('craft_') || id === 'rover') return 'transport'
  if (id.startsWith('monorail_')) return 'transport'
  if (id.startsWith('terrain_') || id === 'terrain') return 'terrain'
  if (id.startsWith('rock') || id.startsWith('meteor') || id.startsWith('crater')) return 'terrain'
  if (id.startsWith('pipe_')) return 'utility'
  if (id.startsWith('machine_') || id.startsWith('barrel')) return 'utility'
  if (id === 'alien' || id.startsWith('astronaut')) return 'character'
  return 'utility'
}


export const RACING_CATEGORY_ORDER = [
  'track',
  'vehicle',
  'venue',
  'facility',
]

export const RACING_CATEGORY_LABELS = {
  track: 'Pist',
  vehicle: 'Yarış Arabası',
  venue: 'Tribün & Pit',
  facility: 'Tabela & Bariyer',
}

export function categorizeRacing(id) {
  if (id.startsWith('raceCar')) return 'vehicle'
  if (id.startsWith('grandStand') || id.startsWith('pits') || id.startsWith('tent')) return 'venue'
  if (id.startsWith('road') || id === 'roadBump') return 'track'
  if (
    id.startsWith('barrier') || id.startsWith('fence') || id.startsWith('light') ||
    id.startsWith('banner') || id.startsWith('billboard') || id.startsWith('flag') ||
    id.startsWith('overhead') || id === 'pylon' || id === 'camera_exclusive'
  ) return 'facility'
  return 'facility'
}


export function categorizeUltimateFood(id) {
  if (/Apple|Avocado|Banana|Broccoli|Carrot|Coconut|Lettuce|Mushroom|Orange|Pepper|Pumpkin|Tomato|Turnip|Eggplant/i.test(id)) return 'produce'
  if (/Donut|Cupcake|Croissant|IceCream|Popsicle|Waffle|Pancake|ChocolateBar/i.test(id)) return 'dessert'
  if (/Bottle|Soda|Ketchup|Mustard|Mayo|SoySauce|PeanutButter/i.test(id)) return 'drink'
  if (/Fork|Knife|Spoon|Chopsticks|Plate|FryingPan|CookingPot|Jar/i.test(id)) return 'kitchen'
  return 'meal'
}

